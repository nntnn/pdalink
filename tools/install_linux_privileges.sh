#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INSTALL_ROOT="${PDALINK_INSTALL_ROOT:-/opt/pdalink}"
LIBEXEC_DIR="${PDALINK_LIBEXEC_DIR:-/usr/local/libexec/pdalink}"
SUDOERS_FILE="${PDALINK_SUDOERS_FILE:-/etc/sudoers.d/pdalink}"
INSTALL_USER="${SUDO_USER:-${USER:-}}"
PYTHON_BIN="${PDALINK_PYTHON_BIN:-$(command -v python3 || true)}"
DRY_RUN=0
UNINSTALL=0

usage() {
  cat <<EOF
Usage: sudo $0 [--user USER] [--install-root PATH] [--libexec-dir PATH] [--sudoers-file PATH] [--python PATH] [--dry-run]
       sudo $0 --uninstall [--sudoers-file PATH]

Installs the root-owned PdaLink Linux helper and a narrow sudoers rule so
runtime commands can use sudo -n without prompting for a password.

Installed root command:
  $LIBEXEC_DIR/pdalink-root

Allowed commands for USER:
  pdalink-root system-start ...
  pdalink-root system-stop ...
  pdalink-root system-down ...
EOF
}

run() {
  if [[ "$DRY_RUN" -eq 1 ]]; then
    printf 'DRY-RUN'
    printf ' %q' "$@"
    printf '\n'
  else
    "$@"
  fi
}

fail() {
  echo "ERROR: $*" >&2
  exit 1
}

require_root() {
  if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then
    fail "run this installer with sudo"
  fi
}

validate_user() {
  [[ -n "$INSTALL_USER" ]] || fail "could not infer target user; pass --user USER"
  if [[ ! "$INSTALL_USER" =~ ^[A-Za-z_][A-Za-z0-9_.-]*[$]?$ ]]; then
    fail "unsafe user name for sudoers: $INSTALL_USER"
  fi
  id "$INSTALL_USER" >/dev/null 2>&1 || fail "user not found: $INSTALL_USER"
}

validate_inputs() {
  [[ -n "$PYTHON_BIN" && -x "$PYTHON_BIN" ]] || fail "python3 not found; pass --python PATH"
  [[ -f "$ROOT/linux/pdalink_lite.py" ]] || fail "missing linux/pdalink_lite.py"
  [[ -f "$ROOT/linux/pdalink_tun.py" ]] || fail "missing linux/pdalink_tun.py"
  command -v visudo >/dev/null 2>&1 || fail "visudo not found"
}

write_root_helper() {
  local helper="$LIBEXEC_DIR/pdalink-root"
  run install -d -m 0755 "$INSTALL_ROOT/linux" "$LIBEXEC_DIR"
  run install -m 0755 "$ROOT/linux/pdalink_lite.py" "$INSTALL_ROOT/linux/pdalink_lite.py"
  run install -m 0644 "$ROOT/linux/pdalink_tun.py" "$INSTALL_ROOT/linux/pdalink_tun.py"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    echo "DRY-RUN write $helper"
    return
  fi
  cat >"$helper" <<EOF
#!/usr/bin/env bash
set -euo pipefail
export PYTHONUNBUFFERED=1
exec "$PYTHON_BIN" "$INSTALL_ROOT/linux/pdalink_lite.py" "\$@"
EOF
  chmod 0755 "$helper"
  chown root:root "$helper" "$INSTALL_ROOT/linux/pdalink_lite.py" "$INSTALL_ROOT/linux/pdalink_tun.py"
}

write_sudoers() {
  local helper="$LIBEXEC_DIR/pdalink-root"
  local tmp
  tmp="$(mktemp)"
  cat >"$tmp" <<EOF
# PdaLink limited privilege rules.
# Generated by tools/install_linux_privileges.sh.
Cmnd_Alias PDALINK_SYSTEM = $helper system-start *, $helper system-stop *, $helper system-down *
$INSTALL_USER ALL=(root) NOPASSWD: PDALINK_SYSTEM
EOF
  visudo -cf "$tmp" >/dev/null
  if [[ "$DRY_RUN" -eq 1 ]]; then
    echo "DRY-RUN write $SUDOERS_FILE"
    cat "$tmp"
    rm -f "$tmp"
    return
  fi
  install -m 0440 -o root -g root "$tmp" "$SUDOERS_FILE"
  rm -f "$tmp"
  visudo -cf "$SUDOERS_FILE" >/dev/null
}

install_privileges() {
  require_root
  validate_user
  validate_inputs
  write_root_helper
  write_sudoers
  local action="installed"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    action="dry-run complete; no files were changed"
  fi
  cat <<EOF
PdaLink Linux privileges $action.

Runtime commands should now work without an interactive sudo prompt:
  ./tools/pdalink.sh system service start --proxy-url http://127.0.0.1:18080
  ./tools/pdalink.sh system service stop --proxy-url http://127.0.0.1:18080

Installed helper:
  $LIBEXEC_DIR/pdalink-root
Sudoers file:
  $SUDOERS_FILE
EOF
}

uninstall_privileges() {
  require_root
  run rm -f "$SUDOERS_FILE"
  run rm -f "$LIBEXEC_DIR/pdalink-root"
  echo "PdaLink Linux privilege rule removed."
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --user)
      INSTALL_USER="${2:-}"
      [[ -n "$INSTALL_USER" ]] || fail "--user requires a value"
      shift 2
      ;;
    --install-root)
      INSTALL_ROOT="${2:-}"
      [[ -n "$INSTALL_ROOT" ]] || fail "--install-root requires a value"
      shift 2
      ;;
    --libexec-dir)
      LIBEXEC_DIR="${2:-}"
      [[ -n "$LIBEXEC_DIR" ]] || fail "--libexec-dir requires a value"
      shift 2
      ;;
    --sudoers-file)
      SUDOERS_FILE="${2:-}"
      [[ -n "$SUDOERS_FILE" ]] || fail "--sudoers-file requires a value"
      shift 2
      ;;
    --python)
      PYTHON_BIN="${2:-}"
      [[ -n "$PYTHON_BIN" ]] || fail "--python requires a value"
      shift 2
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    --uninstall)
      UNINSTALL=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
done

if [[ "$UNINSTALL" -eq 1 ]]; then
  uninstall_privileges
else
  install_privileges
fi
